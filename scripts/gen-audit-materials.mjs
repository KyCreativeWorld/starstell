// Bundles the LLM prompts and briefs in audit_process/phase_N/ into the app, so the
// web build (GitHub Pages) can send them to the model without reading local folders.
//
// For each phase folder it reads:
//   p<N>_prompt.txt            -> the system prompt
//   every other .md / .txt     -> reference documents (e.g. the phase brief)
// PDFs are skipped: write the brief as .md so the app can send it as text.
//
// Writes src/audit/generated/auditMaterials.ts. Runs before every web build
// (npm run build:html) and on its own with: npm run gen:audit

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'audit_process');
const outFile = join(root, 'src', 'audit', 'generated', 'auditMaterials.ts');

const phases = {};
for (let n = 1; n <= 5; n++) {
  const dir = join(srcDir, `phase_${n}`);
  if (!existsSync(dir)) continue;
  const promptName = `p${n}_prompt.txt`;
  const files = readdirSync(dir).filter((f) => !f.startsWith('.')).sort();
  const prompt = files.includes(promptName) ? readFileSync(join(dir, promptName), 'utf8').trim() : null;
  const documents = files
    .filter((f) => f !== promptName && /\.(md|txt)$/i.test(f))
    .map((f) => ({ name: f, text: readFileSync(join(dir, f), 'utf8').trim() }));
  const skipped = files.filter((f) => /\.pdf$/i.test(f));
  if (skipped.length) console.warn(`gen-audit-materials: phase_${n}: skipped ${skipped.join(', ')} (convert to .md to include)`);
  if (prompt || documents.length) phases[n] = { prompt, documents };
}

const body = `// GENERATED by scripts/gen-audit-materials.mjs from audit_process/. Do not edit by hand;
// edit the files in audit_process/ and run \`npm run gen:audit\`.

export interface AuditDocument {
  name: string;
  text: string;
}

export interface PhaseMaterials {
  /** System prompt (p<N>_prompt.txt), or null if the phase has none yet. */
  prompt: string | null;
  /** Reference documents sent with the prompt, e.g. the phase brief. */
  documents: AuditDocument[];
}

export const AUDIT_MATERIALS: Partial<Record<1 | 2 | 3 | 4 | 5, PhaseMaterials>> = ${JSON.stringify(phases, null, 2)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
console.log(`✔ Wrote ${outFile} (phases: ${Object.keys(phases).join(', ') || 'none'})`);
