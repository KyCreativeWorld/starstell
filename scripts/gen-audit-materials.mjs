// Bundles the LLM prompts and briefs in audit_process/phase_N/ into the app, so the
// web build (GitHub Pages) can send them to the model without reading local folders.
//
// For each phase folder it reads:
//   p<N>_prompt.txt        -> the phase prompt, sent with every step in the phase
//   step_<M>_prompt.txt    -> a step's own instructions; a step runs only if it has one
//   other .md / .txt       -> reference documents (e.g. the phase brief)
//   .pdf                   -> reference documents too; embedded and turned into text in the app
//
// Writes src/audit/generated/auditMaterials.ts. Runs before `npm start`, `npm run web`
// and `npm run build:html`, and on its own with: npm run gen:audit

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = join(root, 'audit_process');
const outFile = join(root, 'src', 'audit', 'generated', 'auditMaterials.ts');

const phases = {};
for (let n = 1; n <= 5; n++) {
  const dir = join(srcDir, `phase_${n}`);
  if (!existsSync(dir)) continue;
  const files = readdirSync(dir).filter((f) => !f.startsWith('.')).sort();
  const read = (f) => readFileSync(join(dir, f), 'utf8').trim();

  const phasePromptName = `p${n}_prompt.txt`;
  const stepPrompts = {};
  for (const f of files) {
    const m = f.match(/^step_(\d+)_prompt\.txt$/i);
    if (m) stepPrompts[Number(m[1])] = read(f);
  }
  const documents = files
    .filter((f) => f !== phasePromptName && !/^step_\d+_prompt\.txt$/i.test(f) && /\.(md|txt)$/i.test(f))
    .map((f) => ({ name: f, text: read(f) }));
  const pdfs = files
    .filter((f) => /\.pdf$/i.test(f))
    .map((f) => ({ name: f, base64: readFileSync(join(dir, f)).toString('base64') }));

  phases[n] = {
    prompt: files.includes(phasePromptName) ? read(phasePromptName) : null,
    stepPrompts,
    documents,
    pdfs,
  };
}

const body = `// GENERATED by scripts/gen-audit-materials.mjs from audit_process/. Do not edit by hand;
// edit the files in audit_process/ and run \`npm run gen:audit\`.

export interface AuditDocument {
  name: string;
  text: string;
}

export interface PhaseMaterials {
  /** Phase prompt (p<N>_prompt.txt), sent with every step of the phase; null if none. */
  prompt: string | null;
  /** Step prompts (step_<M>_prompt.txt), keyed by step number. A step runs only if it has one. */
  stepPrompts: Record<number, string>;
  /** Text reference documents, e.g. the phase brief. */
  documents: AuditDocument[];
  /** PDF reference documents, base64; turned into text by the app. */
  pdfs: { name: string; base64: string }[];
}

export const AUDIT_MATERIALS: Partial<Record<number, PhaseMaterials>> = ${JSON.stringify(phases)};
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, body);
const summary = Object.entries(phases)
  .map(([n, p]) => `phase ${n}: steps [${Object.keys(p.stepPrompts).join(', ')}], ${p.documents.length + p.pdfs.length} doc(s)`)
  .join('; ');
console.log(`✔ Wrote ${outFile} (${summary})`);
